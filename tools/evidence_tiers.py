"""Evidence tiers for MediaDB component mappings.

One vocabulary, one place. `map_metabolite.Mapper` mints a tier for every mapping
it makes; this module additionally classifies the mapping_method values already
present in the shipped corpus, so a component that was written by some other
builder can be given an honest tier without re-guessing its identity.

THE RULE THIS FILE ENFORCES: a tier states what the mapping was ACTUALLY decided
on. It is never raised because the result looks right, and a route whose evidence
was destroyed gets the FLOOR of what it could have been, never the ceiling.
"""

# Ordered strongest to weakest. See map_metabolite.__doc__ for the definitions.
TIER_ORDER = [
    "structural_xref",      # source chemistry key resolved through the reverse index
    "curated_mapping",      # reviewed row in tools/curation/metabolite_corrections.tsv
    "author_asserted",      # a curator/recipe author asserted it; no chemical justification
    "source_bigg_id",       # the source supplied a BiGG id; an id-string route
    "exact_name",           # stereo-correct exact match against a BiGG name/synonym
    "name_table",           # hand-typed source-name -> BiGG table, unreviewed
    "fuzzy_name",           # normalised / alias / de-formula / heuristic name match
    "class_proxy",          # a class, vitamer group or element -> one species
    "derived_component",    # generated by the pipeline, not stated by the source
    "non_bigg_fallback",    # ModelSEED/MetaNetX/KEGG pseudo-exchange, not BiGG
    "unmappable_mixture",   # undefined mixture; no single exchange is defensible
    "unmapped",             # no confident target. Absent, not guessed.
]
TIER_RANK = {t: i for i, t in enumerate(TIER_ORDER)}

# Tiers that do NOT represent an observation of the medium's stated composition.
# Excluded from coverage arithmetic by operator decision (segregate and label).
#
# Only `derived_component` qualifies. An unmappable mixture and a refused mapping
# WERE stated by the source -- yeast extract really is in the medium; we simply
# cannot give it one exchange. They stay in the observed denominator and count as
# NOT COVERED, which is the honest way round: excluding them would flatter coverage
# by deleting the hardest cases, which is the defect this whole pass exists to undo.
NON_OBSERVED_TIERS = {"derived_component"}

# Tiers whose identity was decided by a name string rather than by chemistry.
NAME_BASED_TIERS = {"exact_name", "name_table", "fuzzy_name", "class_proxy"}

