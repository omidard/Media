def tier_for_method(method):
    """(tier, remappable, note). Unknown methods get the floor, never the ceiling."""
    return METHOD_TIERS.get(method, ("fuzzy_name", False,
                                     f"unrecognised mapping_method {method!r}; "
                                     "recorded at the weakest name tier"))


def is_stronger(a, b):
    """True when tier `a` rests on stronger evidence than tier `b`."""
    return TIER_RANK.get(a, 99) < TIER_RANK.get(b, 99)
